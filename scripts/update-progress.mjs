import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import { createHash } from "node:crypto";
const read = (p) => JSON.parse(readFileSync(p));
const pkg = read("package.json"),
  lock = read("package-lock.json"),
  roadmap = read("docs/roadmap.json");
const deployment = read("deployments/11155111.json");
const seed = existsSync("deployments/11155111.seed.json")
  ? read("deployments/11155111.seed.json")
  : null;
const published = existsSync("deployments/website.json")
  ? read("deployments/website.json")
  : null;
function files(path) {
  return readdirSync(path, { withFileTypes: true }).flatMap((d) =>
    d.isDirectory() ? files(`${path}/${d.name}`) : [`${path}/${d.name}`],
  );
}
const sources = [
  "README.md",
  ".env.example",
  "package.json",
  "package-lock.json",
  "next.config.mjs",
  "tsconfig.json",
  "AGENTS.md",
  ...[
    "app",
    "lib",
    "src/contracts",
    "scripts",
    "test/v1",
    "test/helpers",
    "test/fixtures",
    "benchmarks",
    ".github",
    "docs",
  ].flatMap(files),
]
  .filter(
    (p) => p !== "docs/PROGRESS.md" && !p.startsWith("benchmarks/results/"),
  )
  .sort();
const hash = createHash("sha256");
for (const file of sources) {
  hash.update(file);
  hash.update(readFileSync(file));
}
for (const m of roadmap.milestones) {
  if (!["planned", "in_progress", "done"].includes(m.status))
    throw new Error(`Invalid status: ${m.id}`);
  if (m.status === "done" && !m.evidence.length)
    throw new Error(`Missing evidence: ${m.id}`);
  for (const file of m.evidence)
    if (!existsSync(file)) throw new Error(`Missing evidence: ${file}`);
}
const done = roadmap.milestones.filter((m) => m.status === "done").length;
const testCount = files("test/v1")
  .filter((f) => f.endsWith(".test.mjs"))
  .reduce(
    (n, f) =>
      n + [...readFileSync(f, "utf8").matchAll(/\btest\s*\(\s*["']/g)].length,
    0,
  );
const installed = (name) =>
  lock.packages[`node_modules/${name}`]?.version ||
  pkg.dependencies?.[name] ||
  pkg.devDependencies?.[name];
const lines = [
  "# Development progress",
  "",
  "> Generated by `npm run docs:update`. Edit `docs/roadmap.json` and the relevant implementation/docs, then regenerate. CI rejects a stale snapshot.",
  "",
  `Source snapshot: \`${hash.digest("hex").slice(0, 16)}\`. This tracks source changes, not a claim that tests passed.`,
  "",
  `**${done}/${roadmap.milestones.length} milestones complete.** Equal-weight milestone count, not an effort or production-readiness estimate.`,
  "",
  "| Milestone | Status | Evidence |",
  "| --- | --- | --- |",
  ...roadmap.milestones.map(
    (m) =>
      `| ${m.id} · ${m.title} | ${m.status} | ${m.evidence.map((p) => `[${p}](../${p})`).join(", ") || "See [roadmap](ROADMAP.md) acceptance criteria"} |`,
  ),
  "",
  "Engineering review: [audit](ENGINEERING_AUDIT.md), [architecture](ARCHITECTURE.md), [threat model](SECURITY_THREAT_MODEL.md), [performance](PERFORMANCE.md), [capability status](ENGINEERING_STATUS.md).",
  "",
  "## Current implementation",
  "",
  `- Next.js ${installed("next")}; React ${installed("react")}; TypeScript ${installed("typescript")}; ethers ${installed("ethers")}.`,
  `- Lightweight Charts ${installed("lightweight-charts")}; UTC candles and volume from confirmed fills.`,
  `- OpenZeppelin ${installed("@openzeppelin/contracts")}; solc ${installed("solc")}; local EVM runner Ganache ${installed("ganache")}.`,
  `- ${testCount} automated test definitions. CI runs the actual tests and production build; see the repository Actions results for pass/fail.`,
  `- Sepolia chain ${deployment.chainId}; exchange deployment block ${deployment.block}.`,
  `- [Token](https://sepolia.etherscan.io/address/${deployment.token}) · [Exchange](https://sepolia.etherscan.io/address/${deployment.exchange}).`,
  seed?.summary
    ? `- Recorded seed completion: ${seed.summary.seededOrders} orders; ${seed.summary.open} open, ${seed.summary.filled} filled, ${seed.summary.cancelled} cancelled at verification time. This is a saved snapshot; live activity may change it.`
    : "- Seed completion not recorded yet.",
  published
    ? `- Public site release: [${published.url}](${published.url}); version ${published.version}; ${published.status}.`
    : "- Public site release metadata not recorded yet.",
  "",
  "## Boundaries",
  "",
  "- Current: static Next.js client + wallet + Sepolia contracts. No application API, persistent off-chain database, indexer, faucet or L2 deployment yet.",
  `- Proposed next network: ${roadmap.proposedL2}.`,
  "- Architecture: [OVERVIEW.md](OVERVIEW.md). Sequenced delivery plan: [ROADMAP.md](ROADMAP.md).",
  "",
];
const output = lines.join("\n");
if (process.argv.includes("--check")) {
  if (
    !existsSync("docs/PROGRESS.md") ||
    readFileSync("docs/PROGRESS.md", "utf8") !== output
  ) {
    console.error(
      "Progress snapshot is stale. Run npm run docs:update and commit docs/PROGRESS.md.",
    );
    process.exitCode = 1;
  } else console.log("Progress snapshot matches the source.");
} else {
  writeFileSync("docs/PROGRESS.md", output);
  console.log("Updated docs/PROGRESS.md");
}
